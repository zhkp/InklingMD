// 文档（标签页）身份（#431 评审）
//
// 路径不能当身份：草稿「另存为」会把路径从 untitled-N 换成真实路径，但仍是
// 同一份文档；反之同路径被外部重载时内容已换掉。异步任务（图片上传等）必须
// 按 docId 判断「目标是否仍是同一份文档」，revision 单独判断内容是否被替换。
//
// docId 是运行期身份，不持久化；同一标签页的对象 spread（另存为、外部改名）
// 会自然保留它，新建/恢复标签页时重新生成。

let seq = 0;

/** 生成一个新的文档身份 */
export function createDocId(): string {
  seq += 1;
  return `doc-${seq}`;
}
